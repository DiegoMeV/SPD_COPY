  CONSTRAINT SPD_GOAL_ACCUM_CK       CHECK (ACCUMULATION_TYPE IN ('STOCK','FLOW','ACCUMULATED','NO_ACCUMULATED',
                                                                  'CAPACITY','REDUCTION','ANNUAL_REDUCTION'))
);
-- Código único por plan. En PostgreSQL los NULL no chocan en un UNIQUE, pero en Oracle
-- (NULL, 'X') se repetiría; por eso el índice solo aplica cuando la meta tiene plan.
CREATE UNIQUE INDEX SPD_GOAL_CODE_UK ON SPD_GOAL (
  CASE WHEN PLAN IS NOT NULL THEN NIT_COMPANIA END,
  CASE WHEN PLAN IS NOT NULL THEN PLAN END,
  CASE WHEN PLAN IS NOT NULL THEN CODE END
);
CREATE INDEX SPD_GOAL_CIA_I     ON SPD_GOAL (NIT_COMPANIA);
CREATE INDEX SPD_GOAL_PARENT_I  ON SPD_GOAL (PARENT_GOAL_ID);
CREATE INDEX SPD_GOAL_LEVEL_I   ON SPD_GOAL (DEV_PLAN_LEVEL_ID);
CREATE INDEX SPD_GOAL_ENT_I     ON SPD_GOAL (ENTITY_ID);
CREATE INDEX SPD_GOAL_PROJECT_I ON SPD_GOAL (NIT_COMPANIA, PROJECT_CODE);
COMMENT ON TABLE  SPD_GOAL                  IS 'Metas de SPD (equivale a "goal" en PostgreSQL)';
COMMENT ON COLUMN SPD_GOAL.EXTRA_ENTITY_IDS IS 'Arreglo JSON de ENTIDADES_PRY.ID adicionales';
COMMENT ON COLUMN SPD_GOAL.ODS_IDS          IS 'Arreglo JSON de SPD_ODS.ID';
COMMENT ON COLUMN SPD_GOAL.LINKED_GOAL_IDS  IS 'Arreglo JSON de SPD_GOAL.ID';
COMMENT ON COLUMN SPD_GOAL.PROJECT_CODE     IS 'Código del proyecto en PROYECTO.PROYECTO (sin FK: en Oracle es NUMBER y aquí texto)';


