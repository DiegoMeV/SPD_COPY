/* =============================================================================
   SPD - Seguimiento a Planes de Desarrollo
   Estructura de tablas para Oracle (esquema SIIF)

   Destino   : Oracle 19c o superior (usa columnas IDENTITY y CHECK IS JSON)
   Origen    : prisma/schema.prisma (PostgreSQL)

   Convenciones
   - Todas las tablas nuevas llevan el prefijo SPD_ y conservan el nombre que
     tienen en PostgreSQL (goal -> SPD_GOAL, monitoring_record -> SPD_MONITORING_RECORD).
   - Se reusan tablas existentes del SIIF:
       COMPANIA         (NIT_COMPANIA)           en lugar de tenant
       ENTIDADES_PRY    (ID)                     en lugar de entity
       PLAN_DESARROLLO  (NIT_COMPANIA, PLAN)     en lugar de dev_plan
       USUARIOS         (NIT_COMPANIA, USUARIO)  en lugar de user_account
       PROYECTO         (NIT_COMPANIA, PROYECTO) en lugar de siif_proyecto
     Los campos propios de SPD de entidades y planes se agregan a ENTIDADES_PRY y
     PLAN_DESARROLLO en siif_spd_columns.sql (ejecutar antes de este script).
   - tenant_id  -> NIT_COMPANIA VARCHAR2(15) con FK a COMPANIA.
   - dev_plan_id -> PLAN NUMBER(2) + NIT_COMPANIA, con FK a PLAN_DESARROLLO (PLAN, NIT_COMPANIA)
                   (PLAN_DESARROLLO.ID no tiene UNIQUE, por eso no se usa).
   - created_by / updated_by -> ID del usuario en USUARIOS.ID (sin FK: esa columna no es única).
   - Booleanos  -> VARCHAR2(1) 'S' / 'N' (convención del SIIF).
   - Enums      -> VARCHAR2 + CHECK.
   - Json / arreglos -> CLOB con CHECK IS JSON.
   - Fechas     -> TIMESTAMP WITH TIME ZONE.
   - IDs        -> GENERATED BY DEFAULT ON NULL AS IDENTITY, para poder migrar
                   los IDs existentes de PostgreSQL y luego dejar que Oracle genere.
   - Columnas NOT NULL con valor por defecto -> DEFAULT ON NULL, porque los
                   formularios (APEX) envían NULL explícito y un DEFAULT normal no aplica.

   Orden de ejecución: el de este archivo (respeta dependencias de FK).
   ============================================================================= */


