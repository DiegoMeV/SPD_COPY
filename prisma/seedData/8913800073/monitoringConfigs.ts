const getSpentDocs = (document: string) => {
  if (document === "COMPROMISO") {
    return [SpentDoc.COMMITMENT];
  } else if (document === "OBLIGACION") {
    return [SpentDoc.OBLIGATION];
  } else if (document === "PAGO") {
    return [SpentDoc.PAYMENT];
  }
  return [SpentDoc.COMMITMENT];
};

type MonitoringColor = "red" | "yellow" | "green";

const getColorsConfig = (colors: Record<MonitoringColor, Array<number>>) => {
  const colorsMap: Record<MonitoringColor, string> = {
    red: "#f5222d",
    yellow: "#fadb14",
    green: "#52c41a",
  };
  return Object.entries(colors).map(([color, range]) => {
    return {
      color: colorsMap[color as MonitoringColor],
      fromValue: range[0],
      toValue: range[1],
      includeFromValue: color === "red",
      includeToValue: true,
    };
  });
};

const getDatesConfig = (dates: Record<string, string>) => {
  return {
    scheduling: [
      dayjs(dates.scheduling, "DD/MM/YY").subtract(14, "days").toDate(),
      dayjs(dates.scheduling, "DD/MM/YY").toDate(),
    ],
    reporting: [
      dayjs(dates.reporting, "DD/MM/YY").subtract(14, "days").toDate(),
      dayjs(dates.reporting, "DD/MM/YY").toDate(),
    ],
    validating: [
      dayjs(dates.reporting, "DD/MM/YY").subtract(14, "days").toDate(),
      dayjs(dates.reporting, "DD/MM/YY").toDate(),
    ],
    reviewing: [
      dayjs(dates.reviewing, "DD/MM/YY").subtract(14, "days").toDate(),
      dayjs(dates.reviewing, "DD/MM/YY").toDate(),
    ],
  };
};

const monitoringConfigs = async (): Promise<Array<Partial<MonitoringConfig>>> => {
  const devPlans = await prisma?.devPlan.findMany({
    where: {
      tenant: {
        key: TENANT_KEY,
      },
    },
  });

  const getDevPlanId = (planCode: string) => {
    const devPlan = devPlans.find((devPlan) => devPlan.code === planCode);
    return devPlan?.id;
  };

  const data = monitoringConfigsData.map((item, index) => {
    return {
      usedFor: MonitoringConfigUsedFor.DEVELOPMENT_PLANS,
      isActive: index === monitoringConfigsData.length - 1,
      devPlanId: getDevPlanId(item.plan),
      period: parseInt(item.periodo),
      subperiod: parseInt(item.subperiodo),
      periodicity: item.periodicidad,
      spentDocs: getSpentDocs(item.documento_ejecucion),
      weightingType: WeightingType.FINANCIAL,
      datesConfig: JSON.parse(
        JSON.stringify(
          getDatesConfig({
            scheduling: item.fecha_limite_pa ?? item.fecha_limite,
            reporting: item.fecha_limite,
            validating: item.fecha_limite,
            reviewing: item.fecha_limite_revisar ?? item.fecha_limite,
          }),
        ),
      ),
      colorsConfig: getColorsConfig({
        red: [
          parseFloat(`${item.rango_inicial_rojo}` ?? "0"),
          parseFloat(`${item.rango_final_rojo}` ?? "0"),
        ],
        yellow: [
          parseFloat(`${item.rango_inicial_amarillo}` ?? "0"),
          parseFloat(`${item.rango_final_amarillo}` ?? "0"),
        ],
        green: [
          parseFloat(`${item.rango_inicial_verde}` ?? "0"),
          parseFloat(`${item.rango_final_verde}` ?? "0"),
        ],
      }),
      status: MonitoringStatus.CLOSED,
      monitoringResourcesOrigin: MonitoringResourcesOrigin.FINANCIAL,
      supportProductMonitoring: false,
      sgpDiscriminated: false,
    };
  });
  return data;
};

